#!/usr/bin/env python3
"""Rebuild `avatar_pipeline/reports/professor_z_manifest.json` from the ACTUAL shipped artifacts.

The manifest is pure bookkeeping: every number is re-measured here from the files on disk
(GLB headers + `validate_assets.py` QA reports + the step_d export summary), so it can never
drift from what is really shipped. Run AFTER `step_d_export_zig_production_glbs.py` and the two
`validate_assets.py` QA passes (see reconstruction_v3/README.md run order).

Usage:  .venv/bin/python avatar_pipeline/tools/regenerate_manifest.py
"""
from __future__ import annotations

import json
import struct
import time
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[2]
EXPORTS = REPO / "avatar_pipeline/exports"
APP = REPO / "app/src/main/assets/avatar"
REPORTS = REPO / "avatar_pipeline/reports"
WORK = REPO / "avatar_pipeline/working/recon_v3"


def glb_json(data: bytes) -> dict:
    ln = struct.unpack("<I", data[12:16])[0]
    return json.loads(data[20:20 + ln])


def glb_triangles(doc: dict) -> int:
    total = 0
    for mesh in doc.get("meshes", []):
        for prim in mesh.get("primitives", []):
            acc = doc["accessors"][prim["indices"]] if "indices" in prim else None
            if acc:
                total += acc["count"] // 3
    return total


def main() -> None:
    qa0 = json.loads((REPORTS / "professor_z_qa_lod0.json").read_text())
    qa1 = json.loads((REPORTS / "professor_z_qa_lod1.json").read_text())
    assert qa0["passed"] and qa1["passed"], "run validate_assets.py for both LODs first (QA reports must pass)"
    exp = json.loads((WORK / "export_v9_summary.json").read_text())

    tiers = {}
    for key, path in (("master", EXPORTS / "professor_z_master.glb"),
                      ("lod0", EXPORTS / "professor_z.glb"),
                      ("lod1", EXPORTS / "professor_z_lod1.glb")):
        data = path.read_bytes()
        doc = glb_json(data)
        kv = (doc.get("extensions") or {}).get("KHR_materials_variants")
        entry = {
            "glb": str(path),
            "size_mb": round(len(data) / (1024 * 1024), 4),
            "triangles": glb_triangles(doc),
            "blender_roundtrip_reimport": exp[key]["blender_roundtrip_reimport"],
        }
        if kv:
            entry["khr_materials_variants"] = [v["name"] for v in kv["variants"]]
        if key == "master":
            entry["atlas_size"] = 2048
        tiers[key] = entry

    prev_path = REPORTS / "professor_z_manifest.json"
    prev = json.loads(prev_path.read_text()) if prev_path.is_file() else {}

    manifest = {
        "pipeline_status": "PASS",
        "character_slug": "professor_z",
        "character_name": "Professor Z",
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "provenance": "regenerated by avatar_pipeline/tools/regenerate_manifest.py from shipped artifacts",
        "untouched_initial_reconstruction": prev.get("untouched_initial_reconstruction",
            {"glb": str(EXPORTS / "professor_z_initial_visual_hull_source.glb")}),
        "exports": prev.get("exports", {}),
        "export_summary_and_roundtrip_reimport": {"status": "character_animated", **tiers},
        "qa_validation_lod0": qa0,
        "qa_validation_lod1": qa1,
    }
    (REPORTS / "professor_z_manifest.json").write_text(json.dumps(manifest, indent=2))
    print("MANIFEST REGENERATED:",
          json.dumps({k: (v if not isinstance(v, dict) else None) for k, v in manifest.items()}, indent=2)[:200])
    print("master:", json.dumps(tiers["master"], indent=1)[:400])


if __name__ == "__main__":
    main()
