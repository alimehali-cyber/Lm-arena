/**
 * AssetKit — offline toolchain that turns primary scientific data into shippable packs.
 * Per §6: deterministic and reproducible, same inputs + same config => byte-identical outputs (verify by hashing twice).
 * CLI verbs per §6.2: fetch, preprocess, tiles, encode, horizon, normal, pack, verify, atmosphere, all with --dry-run
 */

data class CliArgs(
    val verb: String,
    val options: Map<String, String>,
    val dryRun: Boolean
)

fun parseArgs(args: Array<String>): CliArgs {
    if (args.isEmpty()) {
        return CliArgs("help", emptyMap(), false)
    }
    val verb = args[0]
    val opts = mutableMapOf<String, String>()
    var dryRun = false
    var i = 1
    while (i < args.size) {
        val arg = args[i]
        if (arg == "--dry-run") {
            dryRun = true
            i++
        } else if (arg.startsWith("--")) {
            val key = arg.removePrefix("--")
            if (i + 1 < args.size && !args[i + 1].startsWith("--")) {
                opts[key] = args[i + 1]
                i += 2
            } else {
                opts[key] = "true"
                i++
            }
        } else {
            // positional?
            i++
        }
    }
    return CliArgs(verb, opts, dryRun)
}

fun main(args: Array<String>) {
    val cli = parseArgs(args)
    if (cli.dryRun) {
        println("[DRY-RUN] Would execute verb: ${cli.verb} with options: ${cli.options}")
    }

    when (cli.verb) {
        "fetch" -> fetch(cli)
        "preprocess" -> preprocess(cli)
        "tiles" -> tiles(cli)
        "encode" -> encode(cli)
        "horizon" -> horizon(cli)
        "normal" -> normal(cli)
        "pack" -> pack(cli)
        "verify" -> verify(cli)
        "atmosphere" -> atmosphere(cli)
        "rings" -> rings(cli)
        "wind" -> wind(cli)
        "help", "--help", "-h" -> printHelp()
        else -> {
            println("Unknown verb: ${cli.verb}")
            printHelp()
        }
    }
}

