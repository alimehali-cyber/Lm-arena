    println("Tiling input=$input out=$out tile=$tileSize apron=$apron")
    if (cli.dryRun) {
        println("[DRY-RUN] Would create tile pyramid per §6.4: tile $tileSize, apron $apron, levels L0 native halved until <=512, naming tiles/L<level>/<x>_<y>.ktx2, seam duplication, pole handling")
        return
    }

    val inputFile = File(input)
    val outDir = File(out)
    outDir.mkdirs()

    // For M2 demo, we create synthetic tile pyramid if input is synthetic
    // Real implementation would read TIFF and create tiles
    // Here we simulate: create L0 with 2x2 tiles, L1 with 1x1, etc.
    // Deterministic and reproducible per §6.1

    // Create levels
    val levels = listOf(0, 1, 2) // L0 native, L1 half, L2 quarter
    for (level in levels) {
        val levelDir = File(outDir, "tiles/L$level")
        levelDir.mkdirs()
        val tilesX = max(1, 2 shr level) // 2,1,1
        val tilesY = max(1, 1 shr level) // 1,1,1
        for (x in 0 until tilesX) {
            for (y in 0 until tilesY) {
                val tileFile = File(levelDir, "${x}_${y}.ktx2")
                // Create placeholder KTX2 file with deterministic content
                // Real KTX2 would have magic, format, dimensions, etc.
                val content = "KTX2 placeholder level=$level x=$x y=$y tile=$tileSize apron=$apron input=$input deterministic".toByteArray()
                tileFile.writeBytes(content)
            }
        }
        // Seam duplication per §6.4: duplicate first column at end of each row
        if (tilesX > 1) {
            for (y in 0 until tilesY) {
                val first = File(levelDir, "0_${y}.ktx2")
                val dup = File(levelDir, "${tilesX}_${y}.ktx2")
                if (first.exists()) {
                    dup.writeBytes(first.readBytes())
                    println("Duplicated seam tile ${dup.name} from ${first.name} per §6.4")
                }
            }
        }
    }

    println("Created tile pyramid at $out with apron $apron, tile $tileSize, levels ${levels.size}")
}

