#!/usr/bin/env python3
"""Compile local orthographic plates and catalogue rules. No network or graphics toolkit needed."""
import argparse, json, math, re, xml.etree.ElementTree as ET
from pathlib import Path
root = Path(__file__).resolve().parents[2]
art = Path(__file__).parent / 'shapes'
assets = root / 'app/src/main/assets/satellites'
core = root / 'app/src/main/java/com/alijafari/red/astronomy/ui/satellites/core'
rows = json.loads((assets/'sat_shape_manifest.json').read_text())
check = argparse.ArgumentParser(); check.add_argument('--check', action='store_true'); args=check.parse_args()
def kt(s): return json.dumps(s, ensure_ascii=False)
def coords(path):
    # Small drawings use only absolute polygon commands, so the geometric bounds are exact.
    points=[]; x=y=0; tokens=iter(re.findall(r'[MLHVZ]|-?\d+(?:\.\d+)?',path))
    for op in tokens:
        if op in ('M','L'): x,y=float(next(tokens)),float(next(tokens))
        elif op=='H': x=float(next(tokens))
        elif op=='V': y=float(next(tokens))
        elif op=='Z': continue
        else: raise ValueError(op)
        points.append((x,y))
    return points
shapes=[]; rules=[]
assert len({r['id'] for r in rows})==len(rows)
for r in rows:
    id=r['id']; svg=ET.parse(art/f'{id}.svg').getroot(); assert svg.attrib['viewBox']=='0 0 64 64'
    paths={p.attrib['id']:p.attrib['d'] for p in svg}; m,l,x=[paths[k] for k in ('M','L-cuts','XL-cuts')]
    pts=coords(m); xs,ys=zip(*pts); w=max(xs)-min(xs); h=max(ys)-min(ys)
    assert max(w,h)==64 and abs(w/h/r['refAspect']-1)<.10 and l and x, id
    # Minimum edge length of marker contour at its actual render size (not the detail plate).
    dp=18 if r['tier']==1 else 12 if id=='starlink' else 14
    # Very short shoulders need not be 1.25dp; the *width* of a branch does. Check every
    # rectilinear section with a scanline halfway between successive vertices, on both axes.
    rectilinear = all(a[0]==b[0] or a[1]==b[1] for a,b in zip(pts,pts[1:]+pts[:1]))
    if rectilinear:
        for a in (0,1):
            levels=sorted(set(p[a] for p in pts))
            for lo,hi in zip(levels,levels[1:]):
                v=(lo+hi)/2; cuts=sorted(p[1-a] for p,q in zip(pts,pts[1:]+pts[:1]) if min(p[a],q[a])<v<max(p[a],q[a]))
                for left,right in zip(cuts[::2],cuts[1::2]): assert (right-left)*dp/64>=1.25,(id,left,right)
    shapes.append(f'    {kt(id)} to Plate({kt(m)}, {kt(l)}, {kt(x)})')
    ids=', '.join(map(str,r['norad'])); names=', '.join('Regex('+kt(n)+', RegexOption.IGNORE_CASE)' for n in r['names']); cats=', '.join('SatCategory.'+c for c in r['categories'])
    rules.append(f'    ShapeRule({kt(id)}, {r["tier"]}, setOf({ids}), listOf({names}), setOf({cats}))')
text='// Generated by tools/satellites/build_shapes.py; edit the SVG or manifest instead.\npackage com.alijafari.red.astronomy.ui.satellites.core\n\ninternal data class Plate(val marker: String, val tileCuts: String, val plateCuts: String)\ninternal val plates = mapOf(\n'+',\n'.join(shapes)+'\n)\ninternal val shapeRules = listOf(\n'+',\n'.join(rules)+'\n)\n'
file=core/'GeneratedPlates.kt'
if args.check: assert file.read_text()==text,'Run tools/satellites/build_shapes.py'
else: file.write_text(text)
print(f'{len(rows)} silhouette plates checked')
